export function buildPrompt({
  targetShop,
  referenceShop,
  forbiddenShop,
  aspectRatio,
}: {
  targetShop: string;
  referenceShop: string;
  forbiddenShop: string;
  aspectRatio: string;
}) {
  return `
สร้างโพสต์โปรโมทราคาไอเทมในเกมแบบมืออาชีพ โดยต้องยึดภาพอ้างอิงอย่างเคร่งครัด

ภาพอ้างอิง:
- ภาพที่ 1: ใช้เป็น background / main visual
- ภาพที่ 2: ใช้ราคาแพ็ค ข้อมูลแพ็ค และรูปไอเทมในเกมเท่านั้น
- ภาพที่ 3: ใช้เป็น reference สำหรับ layout, spacing, card layout, typography hierarchy และ UI structure

ข้อมูลร้าน:
- ร้านของเรา: ${targetShop}
- layout อ้างอิงจากร้าน: ${referenceShop}
- ห้ามใช้ UI/CI ของร้าน: ${forbiddenShop}

กติกาสำคัญ:
1. ห้ามสร้างสินค้า ราคา หรือแพ็คใหม่เอง
2. ราคา แพ็ค จำนวนไอเทม และรูปไอเทม ต้องมาจากภาพที่ 2 เท่านั้น
3. ห้ามเปลี่ยนข้อความราคา ตัวเลข หรือข้อมูลแพ็คจากภาพที่ 2
4. ใช้ background/main visual จากภาพที่ 1
5. จัด layout ตามภาพที่ 3 ให้ใกล้เคียงที่สุด
6. ใช้ CI/UI ของร้าน ${targetShop} เท่านั้น
7. ห้ามใช้ CI/UI, สี, โลโก้, ฟอนต์ หรือ visual identity ของ ${forbiddenShop}
8. ห้ามสร้างตัวละคร เกม หรือภาพประกอบใหม่ที่ไม่อยู่ในภาพอ้างอิง
9. ต้องเป็นภาพโปรโมทราคาไอเทมเกม อ่านง่าย เหมาะสำหรับโพสต์ขายจริง
10. สร้างภาพในอัตราส่วน ${aspectRatio}

กติกาเฉพาะสำหรับแพ็คราคา:
11. แพ็คราคา/การ์ดราคา/กล่องสินค้า ต้องใช้ UI, สี, เส้นขอบ, ปุ่ม, เงา และรูปแบบกรอบของร้าน ${targetShop} เท่านั้น
12. ห้ามใช้หน้าตาการ์ดราคา สีปุ่ม สีกรอบ layout กล่องสินค้า หรือ style ของร้าน ${forbiddenShop}
13. ข้อมูลภายในแพ็ค เช่น จำนวนไอเทม ราคา และรูปไอเทม ต้องมาจากภาพที่ 2 แต่ต้อง redraw/จัดวางใหม่ให้เข้ากับ CI ของร้าน ${targetShop}
14. ถ้า UI ของภาพที่ 2 หรือภาพที่ 3 ขัดกับ CI ของร้าน ${targetShop} ให้คงเฉพาะข้อมูลสินค้าและราคา แต่เปลี่ยน visual style ให้เป็นของ ${targetShop}
15. ห้าม copy กล่องราคาแบบเดิมจากภาพที่ 2 ทั้งชุด
16. ให้ทำ price card ใหม่ที่ดูเป็นของร้าน ${targetShop} อย่างชัดเจน

ผลลัพธ์:
- เป็นโพสต์โปรโมทไอเทมเกม 1 ภาพ
- เน้นราคาและแพ็คสินค้า
- คมชัด สะอาด มืออาชีพ
- ห้ามหลุดไปเป็นโปสเตอร์เกมทั่วไป
`;
}

export function buildRefinePrompt({
  editInstruction,
  targetShop,
  referenceShop,
  forbiddenShop,
  aspectRatio,
}: {
  editInstruction: string;
  targetShop?: string;
  referenceShop?: string;
  forbiddenShop?: string;
  aspectRatio?: string;
}) {
  return `
แก้ไขภาพโปรโมทราคาไอเทมเกมจากภาพผลลัพธ์เดิมที่แนบมา

คำสั่งแก้ไขจากผู้ใช้:
${editInstruction}

บริบทเดิม:
- ร้านของเรา: ${targetShop || "ไม่ระบุ"}
- layout อ้างอิงจากร้าน: ${referenceShop || "ไม่ระบุ"}
- ห้ามใช้ UI/CI ของร้าน: ${forbiddenShop || "ไม่ระบุ"}
- อัตราส่วนภาพ: ${aspectRatio || "คงอัตราส่วนเดิม"}

กติกาการแก้ไข:
1. ห้ามสร้างภาพใหม่ทั้งหมดจากศูนย์
2. ให้แก้เฉพาะจุดที่ผู้ใช้ร้องขอ
3. รักษา layout เดิม composition เดิม และข้อมูลเดิมให้มากที่สุด
4. ห้ามเปลี่ยนราคา จำนวนแพ็ค ชื่อแพ็ค หรือข้อมูลสินค้าเดิมโดยไม่ได้รับคำสั่ง
5. ห้ามเปลี่ยนเกม/ไอเทมหลักให้กลายเป็นอย่างอื่น
6. ถ้าผู้ใช้ขอแก้แพ็คราคา ให้ปรับเฉพาะ UI ของการ์ดราคา สี กรอบ ปุ่ม spacing และ readability
7. แพ็คราคา/การ์ดราคา ต้องเข้ากับ CI ของร้าน ${targetShop || "ร้านของเรา"} เท่านั้น
8. ห้ามใช้ visual identity ของ ${forbiddenShop || "ร้านที่ห้ามใช้"} โดยเด็ดขาด
9. ให้ภาพยังดูเป็นโพสต์ขายไอเทมเกมระดับมืออาชีพ
10. คงอัตราส่วนภาพเป็น ${aspectRatio || "อัตราส่วนเดิม"}

เป้าหมาย:
- ปรับภาพเดิมให้ดีขึ้นตามคำสั่ง
- คงความต่อเนื่องจากภาพผลลัพธ์ล่าสุด
- ไม่หลุดจากโจทย์โปรโมทราคาไอเทมเกม
`;
}